/* Turn an ASCII map into the shapes the game actually simulates. Runs of solid
 * tiles are merged into as few rectangles as possible: fewer rectangles means
 * fewer internal edges for the player to snag on while running along a floor. */
function buildLevel(def) {
  const rows = def.rows;
  const h = rows.length;
  const w = rows[0].length;
  const solidAt = (x, y) => x >= 0 && x < w && y >= 0 && y < h && rows[y][x] === '#';

  // Greedy merge: horizontal runs first, then stack identical runs vertically.
  const used = Array.from({ length: h }, () => new Array(w).fill(false));
  const solids = [];
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      if (!solidAt(x, y) || used[y][x]) continue;
      let x2 = x;
      while (x2 + 1 < w && solidAt(x2 + 1, y) && !used[y][x2 + 1]) x2++;
      let y2 = y;
      for (;;) {
        const ny = y2 + 1;
        if (ny >= h) break;
        let full = true;
        for (let i = x; i <= x2; i++) if (!solidAt(i, ny) || used[ny][i]) { full = false; break; }
        if (!full) break;
        y2 = ny;
      }
      for (let j = y; j <= y2; j++) for (let i = x; i <= x2; i++) used[j][i] = true;
      solids.push({ x: x * TILE, y: y * TILE, w: (x2 - x + 1) * TILE, h: (y2 - y + 1) * TILE });
    }
  }

  const spikes = [];
  const coins = [];
  const checkpoints = [];
  let spawn = { x: TILE, y: 0 };
  let cake = null;

  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const ch = rows[y][x];
      const px = x * TILE;
      const py = y * TILE;
      if (ch === '^') {
        // Forgiving hitbox: only the upper part of the tile, inset from the sides.
        spikes.push({ x: px + 4, y: py + 18, w: TILE - 8, h: TILE - 18, dir: 'up', tx: px, ty: py });
      } else if (ch === 'v') {
        spikes.push({ x: px + 4, y: py, w: TILE - 8, h: TILE - 18, dir: 'down', tx: px, ty: py });
      } else if (ch === '*') {
        coins.push({ x: px + TILE / 2, y: py + TILE / 2, taken: false, seed: coins.length * 1.7 });
      } else if (ch === 'f') {
        checkpoints.push({ x: px + TILE / 2, y: py + TILE, active: false });
      } else if (ch === 'P') {
        spawn = { x: px + TILE / 2, y: py + TILE };
      } else if (ch === 'c') {
        cake = { x: px + TILE / 2, y: py + TILE };
      }
    }
  }

  return {
    ...def,
    cols: w,
    rowCount: h,
    width: w * TILE,
    height: h * TILE,
    solids,
    spikes,
    coins,
    checkpoints,
    spawn,
    cake,
    // Anything below this line has fallen out of the world.
    deathY: h * TILE + 220,
  };
}
